def seed_all(target_engine=None):
    use_engine = target_engine if target_engine is not None else engine
    print("Connecting to database to seed sample guides...")
    now = datetime.now(timezone.utc)
    today = date.today()

    with Session(use_engine) as session:
        # 1. Seed Categories
        print("1. Seeding Categories...")
        for cat_data in CATEGORIES_DATA:
            existing = session.exec(select(Category).where(Category.name == cat_data["name"])).first()
            if not existing:
                cat = Category(
                    name=cat_data["name"],
                    display_name=cat_data["display_name"],
                    display_order=cat_data["display_order"],
                )
                session.add(cat)
                print(f"   + Created Category: {cat_data['name']}")
            else:
                existing.display_name = cat_data["display_name"]
                existing.display_order = cat_data["display_order"]
                session.add(existing)
                print(f"   ~ Updated Category: {cat_data['name']}")
        session.commit()

        # 2. Seed Platforms
        print("2. Seeding Platforms...")
        for plat_data in PLATFORMS_DATA:
            existing = session.exec(select(Platform).where(Platform.name == plat_data["name"])).first()
            if not existing:
                p = Platform(
                    name=plat_data["name"],
                    display_name=plat_data["display_name"],
                    official_url=plat_data["official_url"],
                    display_order=plat_data["display_order"],
                )
                session.add(p)
                print(f"   + Created Platform: {plat_data['name']}")
            else:
                existing.display_name = plat_data["display_name"]
                existing.official_url = plat_data["official_url"]
                existing.display_order = plat_data["display_order"]
                session.add(existing)
                print(f"   ~ Updated Platform: {plat_data['name']}")
        session.commit()

        # 3. Seed Articles and Availabilities
        print("3. Seeding Articles & Availabilities...")
        for art_data in ARTICLES_DATA:
            slug = art_data["slug"]
            existing = session.exec(select(Article).where(Article.slug == slug)).first()
            
            if not existing:
                art = Article(
                    slug=slug,
                    title=art_data["title"],
                    anime_title_hi=art_data.get("anime_title_hi"),
                    anime_title_en=art_data.get("anime_title_en"),
                    is_featured=art_data.get("is_featured", False),
                    meta_description=art_data["meta_description"],
                    content_md=art_data["content_md"],
                    category=art_data["category"],
                    published_at=now,
                    created_at=now,
                    updated_at=now,
                    reading_time_minutes=art_data["reading_time_minutes"],
                    platform_links_count=len(art_data["availabilities"]),
                    last_checked=now,
                    cover_image=COVERS_MAP.get(slug),
                )
                session.add(art)
                session.flush()
                print(f"   + Created Article: {slug}")
            else:
                art = existing
                art.title = art_data["title"]
                art.anime_title_hi = art_data.get("anime_title_hi")
                art.anime_title_en = art_data.get("anime_title_en")
                art.is_featured = art_data.get("is_featured", False)
                art.meta_description = art_data["meta_description"]
                art.content_md = art_data["content_md"]
                art.category = art_data["category"]
                art.published_at = art.published_at or now
                art.updated_at = now
                art.reading_time_minutes = art_data["reading_time_minutes"]
                art.platform_links_count = len(art_data["availabilities"])
                art.cover_image = COVERS_MAP.get(slug) or art.cover_image
                session.add(art)
                print(f"   ~ Updated Article: {slug}")

            # Availability mappings
            for avail_data in art_data["availabilities"]:
                pid = avail_data["platform_id"]
                ex_avail = session.exec(
                    select(Availability).where(
                        Availability.article_id == art.id,
                        Availability.platform_id == pid,
                    )
                ).first()
                if not ex_avail:
                    avail = Availability(
                        article_id=art.id,
                        platform_id=pid,
                        languages=avail_data["languages"],
                        hindi_dub=avail_data["hindi_dub"],
                        status=avail_data["status"],
                        notes=avail_data.get("notes", ""),
                        last_checked=today,
                    )
                    session.add(avail)
                else:
                    ex_avail.languages = avail_data["languages"]
                    ex_avail.hindi_dub = avail_data["hindi_dub"]
                    ex_avail.status = avail_data["status"]
                    ex_avail.notes = avail_data.get("notes", "")
                    ex_avail.last_checked = today
            # Seed category links
            if art.category:
                ex_cat_link = session.exec(
                    select(ArticleCategoryLink).where(
                        ArticleCategoryLink.article_id == art.id,
                        ArticleCategoryLink.category_name == art.category
                    )
                ).first()
                if not ex_cat_link:
                    session.add(ArticleCategoryLink(article_id=art.id, category_name=art.category))
            session.commit()

